#!/usr/bin/env python3
"""Refreshes tools/food-saturation/item_ids.json from AsakiYuki/minecraft-item-id-viewer.

That project publishes an Item ID viewer pack for every Minecraft release
(build/stable.mcpack, build/preview.mcpack) whose ui/ui_common.json maps
"#item_id:<n>" -> "minecraft:<name>". We download the published pack (nothing
from the project is vendored) and keep only the foods listed in foods.json.

    python tools/update_item_ids.py [--channel stable|preview] [--build]

Prints CHANGED or UNCHANGED so CI can commit only when something moved.
"""
import argparse
import io
import json
import re
import subprocess
import sys
import urllib.request
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent / "food-saturation"
URL = "https://raw.githubusercontent.com/AsakiYuki/minecraft-item-id-viewer/main/build/{}.mcpack"


def fetch_map(channel):
    req = urllib.request.Request(URL.format(channel), headers={"User-Agent": "pepes-portfolio-item-id-updater"})
    with urllib.request.urlopen(req, timeout=60) as r:
        z = zipfile.ZipFile(io.BytesIO(r.read()))

    def load(name):
        text = z.read(name).decode("utf8")
        return json.loads(text[text.index("{"):])  # skip the generated-by header comment

    found = re.search(r"\(([\d.]+)", load("manifest.json")["header"]["name"])
    version = found.group(1) if found else "unknown"
    ids = {}
    for entry in load("ui/ui_common.json").values():
        if not isinstance(entry, dict):
            continue
        for key, value in (entry.get("property_bag") or {}).items():
            if key.startswith("#item_id:") and isinstance(value, str) and value.startswith("minecraft:"):
                ids[value[len("minecraft:"):]] = int(key.split(":")[1])
    if len(ids) < 500:
        sys.exit(f"Only found {len(ids)} item IDs, the viewer pack format probably changed.")
    return version, ids


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--channel", choices=["stable", "preview"], default="stable")
    ap.add_argument("--build", action="store_true", help="rebuild the Food Saturation pack afterwards")
    args = ap.parse_args()

    foods = json.loads((HERE / "foods.json").read_text("utf8"))
    version, all_ids = fetch_map(args.channel)
    missing = [n for n in foods if n not in all_ids]
    if missing:
        sys.exit(f"Not in {version} {args.channel}: {', '.join(missing)}. Update foods.json.")

    new = {"_comment": "Auto-generated by tools/update_item_ids.py from AsakiYuki/minecraft-item-id-viewer. Do not edit.",
           "game_version": version, "channel": args.channel, "ids": {n: all_ids[n] for n in sorted(foods)}}
    path = HERE / "item_ids.json"
    old = json.loads(path.read_text("utf8")) if path.exists() else None
    if old == new:
        print(f"UNCHANGED ({version} {args.channel})")
    else:
        path.write_text(json.dumps(new, indent=2) + "\n", "utf8")
        moved = [n for n in foods if old and old["ids"].get(n) != new["ids"][n]]
        print(f"CHANGED -> {version} {args.channel}; {len(moved)} food ID(s) moved")
    if args.build:
        subprocess.check_call([sys.executable, str(HERE / "build.py")])


if __name__ == "__main__":
    main()
